-- Prompt Maker Web: Supabase schema setup
-- Run this in Supabase Dashboard > SQL Editor > New query.
-- This creates the prompts table and public image bucket.
-- Security: public visitors can read published prompts and public images.
-- Browser-side admin writes are intentionally NOT enabled here; Firebase Auth is separate
-- from Supabase Auth. Admin writes must go through a server/Edge Function that verifies
-- the Firebase ID token before allowing insert/update/delete or image upload.

create table if not exists public.prompts (
  id bigint generated by default as identity primary key,
  title text not null,
  category text not null default 'Other',
  prompt_text text not null,
  image_url text,
  status text not null default 'draft' check (status in ('draft', 'published')),
  published boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  published_at timestamptz
);

-- Keep older records/app logic consistent when status/published is provided.
create index if not exists prompts_status_published_at_idx
  on public.prompts (status, published_at desc);
create index if not exists prompts_created_at_idx
  on public.prompts (created_at desc);

alter table public.prompts enable row level security;

drop policy if exists "Public can read published prompts" on public.prompts;
create policy "Public can read published prompts"
  on public.prompts for select
  to anon, authenticated
  using (status = 'published' or published = true);

-- Ensure no broad browser-side write policies are left behind.
drop policy if exists "Public can insert prompts" on public.prompts;
drop policy if exists "Public can update prompts" on public.prompts;
drop policy if exists "Public can delete prompts" on public.prompts;
drop policy if exists "Admin can manage prompts" on public.prompts;

-- Create a public bucket for prompt thumbnails/images.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('prompt-images', 'prompt-images', true, 10485760,
        array['image/jpeg','image/png','image/webp','image/gif'])
on conflict (id) do update
set public = true,
    file_size_limit = 10485760,
    allowed_mime_types = array['image/jpeg','image/png','image/webp','image/gif'];

drop policy if exists "Public can view prompt images" on storage.objects;
create policy "Public can view prompt images"
  on storage.objects for select
  to anon, authenticated
  using (bucket_id = 'prompt-images');

-- No anon/authenticated INSERT, UPDATE, or DELETE policy is added intentionally.
-- Use a Firebase-token-verifying Supabase Edge Function for secure admin writes/uploads.
